import random
import streamlit as st

st.set_page_config(
    page_title="Ayo Berhitung!",
    page_icon="🍎",
    layout="centered"
)

# Tampilan berwarna dan ramah anak
st.markdown("""
<style>
.stApp {
    background-color: #FFF5E6;
}
h1 {
    color: #FF6B6B;
    text-align: center;
}
.kartu {
    background: #E5F4FF;
    padding: 20px;
    border-radius: 18px;
    text-align: center;
    margin-bottom: 15px;
}
.benda {
    font-size: 35px;
    overflow-wrap: anywhere;
}
</style>
""", unsafe_allow_html=True)

st.title("🌈 Ayo Berhitung!")
st.markdown(
    "<p style='text-align:center'>"
    "Belajar matematika sambil bermain 🍎"
    "</p>",
    unsafe_allow_html=True
)

# Menyiapkan data permainan
if "nomor" not in st.session_state:
    st.session_state.nomor = 1
    st.session_state.skor = 0
    st.session_state.dijawab = False
    st.session_state.operasi_lama = "Penjumlahan"
    st.session_state.hasil = None
    st.session_state.a = 0
    st.session_state.b = 0

def soal_baru(operasi):
    if operasi == "Penjumlahan":
        a = random.randint(0, 10)
        b = random.randint(0, 10 - a)
        hasil = a + b
        simbol = "+"
        emoji = "🍎"
    else:
        a = random.randint(0, 10)
        b = random.randint(0, a)
        hasil = a - b
        simbol = "−"
        emoji = "🍊"

    st.session_state.a = a
    st.session_state.b = b
    st.session_state.hasil = hasil
    st.session_state.simbol = simbol
    st.session_state.emoji = emoji
    st.session_state.dijawab = False

if st.session_state.hasil is None:
    soal_baru("Penjumlahan")

operasi = st.radio(
    "Pilih latihan:",
    ["Penjumlahan", "Pengurangan"],
    horizontal=True
)

# Jika operasi diubah, mulai sesi baru
if operasi != st.session_state.operasi_lama:
    st.session_state.operasi_lama = operasi
    st.session_state.nomor = 1
    st.session_state.skor = 0
    soal_baru(operasi)
    st.rerun()

st.progress(
    min(st.session_state.nomor - 1, 10) / 10,
    text=f"Soal {min(st.session_state.nomor, 10)} dari 10"
)

st.subheader(f"⭐ Skor: {st.session_state.skor}")

# Tampilkan gambar benda
a = st.session_state.a
b = st.session_state.b
emoji = st.session_state.emoji

gambar_a = emoji * a if a else "Tidak ada benda"
gambar_b = emoji * b if b else "Tidak ada benda"

st.markdown(
    f"""
    <div class="kartu">
        <div class="benda">{gambar_a}</div>
        <h2>{a} {st.session_state.simbol} {b} = ?</h2>
        <div class="benda">{gambar_b}</div>
        <p>Ayo hitung dengan teliti!</p>
    </div>
    """,
    unsafe_allow_html=True
)

# Form jawaban
if st.session_state.nomor <= 10:
    with st.form(
        key=f"form_{operasi}_{st.session_state.nomor}"
    ):
        jawaban = st.number_input(
            "Masukkan jawabanmu:",
            min_value=0,
            max_value=20,
            step=1,
            value=0
        )

        periksa = st.form_submit_button(
            "✅ Periksa Jawaban",
            use_container_width=True,
            disabled=st.session_state.dijawab
        )

    if periksa and not st.session_state.dijawab:
        st.session_state.dijawab = True

        if jawaban == st.session_state.hasil:
            st.session_state.skor += 10
            st.success("🎉 Hebat! Jawabanmu benar!")
        else:
            st.info(
                f"Belum tepat. Jawaban yang benar "
                f"adalah {st.session_state.hasil}. "
                "Tetap semangat!"
            )

    elif st.session_state.dijawab:
        st.info("Jawaban sudah diperiksa. Ayo lanjut!")

    if st.session_state.dijawab:
        if st.session_state.nomor < 10:
            if st.button(
                "➡️ Soal Berikutnya",
                use_container_width=True
            ):
                st.session_state.nomor += 1
                soal_baru(operasi)
                st.rerun()
        else:
            st.balloons()
            st.success(
                f"🏆 Permainan selesai! "
                f"Skor akhir: {st.session_state.skor} dari 100"
            )

            if st.button(
                "🔄 Main Lagi",
                use_container_width=True
            ):
                st.session_state.nomor = 1
                st.session_state.skor = 0
                soal_baru(operasi)
                st.rerun()